#!/usr/bin/env python
"""Wave-12 follow-up executor (host-agnostic; run on the box hosting the runs).

Invoked by hourly_steward.py locally AND over SSH on the remote H100. Duties:

1. TEST-AFTER-TRAIN: for every wave-12 variant work_dir
   (work_dirs/amr_benchmark_retune/*/deepsig201610A/*_w12*), if training is
   finished (no train.py proc references its config) and there is a best
   checkpoint but no amc_test_metrics.json, run tools/test.py. The wave-12
   orchestrators were partly detached, so nothing else guarantees testing.
2. STAGE CHAIN: when the FastMLDNN author stage-1 (author_stage1_ms3200_w12)
   completes, write + launch the author stage-2 fine-tune from its best-val
   checkpoint (dp=0.07, beta=0.5, constant lr 1.054e-4) — the paper's actual
   two-stage pipeline. Idempotent: skipped once the stage-2 dir has ckpts or a
   live proc.
3. Report JSON to stdout: {running, tested, launched, done, warnings}.

All launches pick the physical GPU with the fewest compute procs and export
CUDA_DEVICE_ORDER=PCI_BUS_ID so placement matches nvidia-smi indices.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(os.environ.get("REPO_ROOT", "/home/citybuster/Projects/ChangShuoRadioRecognition"))
PY = os.environ.get(
    "PYTHON", "/home/citybuster/Applications/conda/envs/ChangShuoRadioRecognition/bin/python"
)
RETUNE = REPO / "work_dirs" / "amr_benchmark_retune"
CFG_DIR = REPO / "configs" / "amr_benchmark" / "retune"
MAX_TESTS_PER_RUN = 2

STAGE1_DIR = RETUNE / "fastmldnn" / "deepsig201610A" / "author_stage1_ms3200_w12"
STAGE2B_VARIANT = "author_stage2_from_stage1_w12"
STAGE2B_DIR = RETUNE / "fastmldnn" / "deepsig201610A" / STAGE2B_VARIANT
STAGE2B_CFG = CFG_DIR / "wave12_fastmldnn_deepsig201610A_author_stage2_from_stage1.py"

STAGE2B_TEMPLATE = '''"""Wave-12: author-exact STAGE-2 from the wave-12 stage-1 best checkpoint.

Auto-generated by wave12_followup.py once author_stage1_ms3200_w12 finished.
Upstream stage-2 recipe: pretrained stage-1 backbone -> dp=0.07 + beta=0.5 at
constant lr 1.054e-4, patient ES. Pipeline identical to stage-1 (no L2).
"""
_base_ = ['./wave12_fastmldnn_deepsig201610A_author_stage1_ms3200.py']

load_from = {load_from!r}

model = dict(backbone=dict(dp=0.07), head=dict(beta=0.5))

optim_wrapper = dict(optimizer=dict(type='Adam', lr=1.054e-4))

param_scheduler = dict(_delete_=True, type='ConstantLR', factor=1)

train_cfg = dict(by_epoch=True, max_epochs=1600, val_interval=1)

custom_hooks = [
    dict(type='EarlyStoppingHook', monitor='accuracy/top1', min_delta=0,
         patience=100, rule='greater'),
]
'''


def sh(cmd: str, timeout: int = 300) -> tuple[int, str]:
    try:
        p = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout)
        return p.returncode, (p.stdout or "") + (p.stderr or "")
    except subprocess.TimeoutExpired:
        return 124, "timeout"


def train_proc_running(needle: str) -> bool:
    rc, out = sh(f"ps aux | grep '[t]rain.py' | grep -F -- '{needle}' | head -1")
    return bool(out.strip())


def newest(paths: list[Path]) -> Path | None:
    paths = [p for p in paths if p.is_file()]
    return max(paths, key=lambda p: p.stat().st_mtime) if paths else None


def least_loaded_gpu() -> str:
    rc, idx_out = sh("nvidia-smi --query-gpu=index,uuid --format=csv,noheader")
    uuid_to_idx = {}
    for line in idx_out.splitlines():
        parts = [x.strip() for x in line.split(",")]
        if len(parts) == 2:
            uuid_to_idx[parts[1]] = parts[0]
    counts = {i: 0 for i in uuid_to_idx.values()}
    rc, app_out = sh("nvidia-smi --query-compute-apps=gpu_uuid --format=csv,noheader")
    for line in app_out.splitlines():
        u = line.strip()
        if u in uuid_to_idx:
            counts[uuid_to_idx[u]] += 1
    return min(counts, key=lambda k: counts[k]) if counts else "0"


def detach(cmd: str, log_path: Path, gpu: str) -> None:
    env = dict(os.environ)
    env["CUDA_DEVICE_ORDER"] = "PCI_BUS_ID"
    env["CUDA_VISIBLE_DEVICES"] = gpu
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("a") as fh:
        subprocess.Popen(
            cmd, shell=True, cwd=str(REPO), env=env,
            stdout=fh, stderr=subprocess.STDOUT,
            start_new_session=True,
        )


def variant_config(vdir: Path) -> Path | None:
    """Repo config for this variant (preferred) or the copy inside the dir."""
    for p in sorted(vdir.glob("wave1[2-9]_*.py")):
        repo_cfg = CFG_DIR / p.name
        return repo_cfg if repo_cfg.is_file() else p
    return None


def wave_dirs() -> list[Path]:
    return sorted(set(RETUNE.glob("*/deepsig201610A/*_w1[2-9]*")))


def main() -> int:
    report = {"running": [], "tested": [], "launched": [], "done": [], "warnings": []}

    tests_started = 0
    for vdir in wave_dirs():
        if not vdir.is_dir():
            continue
        name = vdir.name
        model = vdir.parent.parent.name
        cfg = variant_config(vdir)
        if cfg is None:
            # Metric-pull-only dirs on the local box hold just amc_test_metrics.json;
            # they are results mirrors, not runs — skip silently.
            if not any(vdir.glob("*.pth")):
                continue
            report["warnings"].append(f"{name}: no wave12/13 config found in dir")
            continue
        if train_proc_running(cfg.name):
            report["running"].append(name)
            continue
        metrics = vdir / "amc_test_metrics.json"
        best = newest(list(vdir.glob("best_accuracy_top1_epoch_*.pth")))
        if metrics.is_file():
            try:
                top1 = json.loads(metrics.read_text()).get("accuracy/top1")
            except (OSError, json.JSONDecodeError):
                top1 = None
            report["done"].append({"variant": name, "model": model, "top1": top1})
            continue
        if best is None:
            report["warnings"].append(f"{name}: finished but no best ckpt (crashed?)")
            continue
        if tests_started >= MAX_TESTS_PER_RUN:
            report["warnings"].append(f"{name}: test deferred (per-run cap)")
            continue
        gpu = least_loaded_gpu()
        detach(
            f"{PY} tools/test.py {cfg} {best} --work-dir {vdir}",
            vdir / "retune.log", gpu,
        )
        report["tested"].append(
            {"variant": name, "model": model, "ckpt": best.name, "gpu": gpu})
        tests_started += 1

    # --- Stage-1 -> Stage-2 chain -------------------------------------------
    stage1_final = STAGE1_DIR / "epoch_3200.pth"
    stage1_best = newest(list(STAGE1_DIR.glob("best_accuracy_top1_epoch_*.pth")))
    stage1_cfg_running = train_proc_running("author_stage1_ms3200")
    stage2_has_ckpt = any(STAGE2B_DIR.glob("*.pth")) if STAGE2B_DIR.is_dir() else False
    stage2_running = train_proc_running(STAGE2B_CFG.name)
    if (
        not stage1_cfg_running
        and stage1_best is not None
        and not stage2_has_ckpt
        and not stage2_running
    ):
        if not stage1_final.is_file():
            report["warnings"].append(
                "stage1 not running and epoch_3200.pth missing — chaining stage2 "
                f"from best anyway ({stage1_best.name})"
            )
        STAGE2B_CFG.write_text(
            STAGE2B_TEMPLATE.format(load_from=str(stage1_best.relative_to(REPO)))
        )
        STAGE2B_DIR.mkdir(parents=True, exist_ok=True)
        gpu = least_loaded_gpu()
        detach(
            f"{PY} tools/train.py {STAGE2B_CFG} --work-dir {STAGE2B_DIR}",
            STAGE2B_DIR / "retune.log", gpu,
        )
        report["launched"].append(
            {"variant": STAGE2B_VARIANT, "from": stage1_best.name, "gpu": gpu}
        )

    print(json.dumps(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
